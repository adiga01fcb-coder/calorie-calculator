def section(anchor, h3, main, extra, intro):
    p = P[main]; por = portion(p)
    out = [f'<article class="seo-item" id="{anchor}">', f'  <h3>{h3}</h3>',
           f'  <p>{html.escape(intro)} <strong>{html.escape(p["n"])}</strong>: <strong>{p["k"]} ккал</strong> на 100 г '
           f'(Б {fmt(p["p"])} г, Ж {fmt(p["f"])} г, У {fmt(p["u"])} г). '
           f'{html.escape(p["pl"][0].upper() + p["pl"][1:])}, {fmt(por["g"],0)} г — около <strong>{por["k"]} ккал</strong>.</p>']
    if extra:
        out.append('  <ul>')
        for e in extra:
            q = P[e]
            out.append(f'    <li>{html.escape(q["n"])} — {q["k"]} ккал на 100 г; {html.escape(q["pl"])}, {fmt(q["pg"],0)} г — {portion(q)["k"]} ккал</li>')
        out.append('  </ul>')
    out.append(f'  <button type="button" class="linkbtn" data-pick="{html.escape(main)}">Посчитать в калькуляторе →</button>')
    out.append('</article>')
    return '\n'.join('        ' + l for l in out)

